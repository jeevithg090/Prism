#!/usr/bin/env node
// Regenerates lib/agents/tools/extensions.ts and lib/features/index.ts from the Labs feature files.
import { readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
const root = process.cwd();
const list = (dir) => { try { return readdirSync(join(root, dir)).filter((f) => f.endsWith(".ts") && !f.endsWith(".test.ts")).map((f) => f.replace(/\.ts$/, "")).sort(); } catch { return []; } };
const id = (k) => k.replace(/[^a-zA-Z0-9]/g, "_");
const tools = list("lib/agents/tools/extra");
writeFileSync(join(root, "lib/agents/tools/extensions.ts"),
  `// Keystone Labs extension tools (generated by scripts/gen-labs-index.mjs; do not edit by hand).\nimport type { AnyTool } from "./types";\n${tools.map((k) => `import { tool as ${id(k)} } from "./extra/${k}";`).join("\n")}\n\nexport const EXTRA_TOOLS: AnyTool[] = [${tools.map(id).join(", ")}];\n`);
const feats = list("lib/features/items");
writeFileSync(join(root, "lib/features/index.ts"),
  `// Keystone Labs features (generated by scripts/gen-labs-index.mjs; do not edit by hand).\nimport type { LabFeature } from "./types";\n${feats.map((k) => `import { feature as ${id(k)} } from "./items/${k}";`).join("\n")}\n\nexport const LAB_FEATURES: LabFeature[] = [${feats.map(id).join(", ")}];\n`);
console.log(`labs index: ${tools.length} tools, ${feats.length} features`);
